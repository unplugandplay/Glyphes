# M4 gate: the Cypher read path, through FFI (ROADMAP.md Phase B, CYPHER.md).
#
# The Nim suite (tests/unit/test_exec.nim) drives the engine from the
# inside; this file drives the seam the way a host does — prepare, step,
# cells, close — over graph data that crossed the boundary as a file. The
# fixture (tests/fixtures/make_fixture.nim) is written by the real Nim
# write path and left with its WAL, so a readonly open exercises recovery
# on the way in.
#
# There is no mutation from Ruby and that is deliberate (ABI.md pin B6:
# mutation is Cypher-only, writes land at M5). What is testable is the
# whole read contract: scoping, three-valued logic, paging, streaming, and
# errors that arrive with the status the PRD promises.

require "minitest/autorun"
require "tmpdir"
require "fileutils"
require_relative "../../lib/glyphes"

class M4Test < Minitest::Test
  FIXTURE = File.expand_path("../fixtures/social.glyph", __dir__)

  def setup
    unless File.exist?(FIXTURE) || File.exist?(FIXTURE + "-wal")
      # The fixture is generated by the real Nim write path and left with
      # its WAL, so it is rebuilt rather than committed (see
      # tests/fixtures/make_fixture.nim). `nimble gemtest` and `nimble gate`
      # both build it first; this is the message for someone who ran the
      # suite directly.
      skip "no fixture — run `nimble fixture` (or `nimble gemtest`)"
    end
    @db = Glyphes::Database.open(FIXTURE, readonly: true)
  end

  def teardown
    @db.close unless @db.closed?
  end

  def col(q, params = {})
    @db.query(q, params).to_a.map(&:first)
  end

  # ---- shape ---------------------------------------------------------

  def test_columns_carry_the_alias_or_the_source_text
    assert_equal ["name"], @db.query("RETURN 1 AS name").columns
    assert_equal ["n.name", "age"],
                 @db.query("MATCH (n:Person) WHERE n.name = 'Alice' RETURN n.name, n.age AS age").columns
  end

  def test_every_scalar_kind_crosses_as_its_ruby_type
    row = @db.query("RETURN 2 AS i, 1.5 AS f, 's' AS s, true AS t, null AS z, [1,2] AS l, {k: 'v'} AS m").first
    assert_equal 2, row[0]
    assert_equal 1.5, row[1]
    assert_equal "s", row[2]
    assert_equal true, row[3]
    assert_nil row[4]
    assert_equal [1, 2], row[5]
    assert_equal({ "k" => "v" }, row[6])
  end

  def test_integers_stay_integers_through_arithmetic
    assert_equal 2, @db.query("RETURN 1 + 1").first[0]
    assert_equal 7, @db.query("RETURN 3 * 2 + 1").first[0]
    assert_equal 1, @db.query("RETURN 7 / 5").first[0]
  end

  def test_a_node_cell_carries_identity
    row = @db.query("MATCH (a:Person)-[e:KNOWS]->(b) WHERE a.name = 'Alice' AND b.name = 'Bob' RETURN a, e, b").first
    assert_equal 3, row.size
    # M7: a node cell materializes as a Glyphes::Node view (RUBY.md §4.1),
    # not a bare id — `row[0].labels` would be a NoMethodError otherwise.
    # What M4 pinned is still pinned: the cell carries the node's identity.
    assert_instance_of Glyphes::Node, row[0]
    assert_instance_of Glyphes::Node, row[2]
    assert_operator row[0].id, :>, 0
    assert_equal "Person", row[0].label
    assert_equal row[0].id, Glyphes::Node.new(@db, row[0].id).id
  end

  # ---- parameters ----------------------------------------------------

  def test_parameters_bind_by_name
    assert_equal ["Alice"], col("MATCH (n:Person) WHERE n.name = $name RETURN n.name", { "name" => "Alice" })
    assert_equal [30], col("RETURN $age", { "age" => 30 })
    assert_equal [[1, 2]], col("RETURN $list", { "list" => [1, 2] })
  end

  def test_a_parameter_its_query_never_names_is_ignored
    # Cypher refuses unknown parameters; the slice binds what the query
    # names and ignores the rest, because the binding sends the whole
    # params hash and a strict reading would make every caller whitelist.
    assert_equal ["Alice"],
                 col("MATCH (n:Person) WHERE n.name = $name RETURN n.name",
                     { "name" => "Alice", "unused" => 1 })
  end

  def test_an_unbound_parameter_reads_as_null
    # $missing is not in the params table, so the comparison is null and
    # the row filters out — three-valued logic at the seam, not an error.
    assert_equal [], col("MATCH (n:Person) WHERE n.name = $missing RETURN n.name")
  end

  # ---- matching ------------------------------------------------------

  def test_a_label_scan_walks_every_member
    assert_equal %w[Alice Bob Carol Dave Eve Frank],
                 col("MATCH (n:Person) RETURN n.name AS name ORDER BY name")
  end

  def test_an_unknown_label_is_an_empty_result_not_an_error
    assert_equal [], col("MATCH (n:NoSuchLabel) RETURN n.name")
  end

  def test_where_compares_and_null_filters_out
    assert_equal %w[Alice Carol Eve],
                 col("MATCH (n:Person) WHERE n.age > 26 RETURN n.name AS name ORDER BY name")
    assert_equal ["Frank"], col("MATCH (n:Person) WHERE n.age IS NULL RETURN n.name AS name")
    # null > 26 is null, not false: Frank has no age and must not appear.
    assert_equal %w[Alice Bob Carol Dave Eve],
                 col("MATCH (n:Person) WHERE n.age >= 25 RETURN n.name AS name ORDER BY name")
  end

  def test_a_missing_property_reads_as_null
    # Frank has a name and a home but no age: the property was never set,
    # which is the null that comes from absence, not from a null value.
    assert_equal [nil], col("MATCH (n:Person) WHERE n.name = 'Frank' RETURN n.age")
  end

  def test_one_hop_expansion
    assert_equal %w[Bob Carol],
                 col("MATCH (a:Person)-[:KNOWS]->(b:Person) WHERE a.name = 'Alice' RETURN b.name AS b ORDER BY b")
  end

  def test_two_hops_in_one_chain
    # Alice → {Bob, Carol} → Dave: both paths reach Dave, so two rows.
    assert_equal %w[Dave Dave],
                 col("MATCH (a:Person)-[:KNOWS]->(b)-[:KNOWS]->(c) WHERE a.name = 'Alice' RETURN c.name AS c")
  end

  def test_an_edge_property_filters_the_traversal
    rows = @db.query("MATCH (a)-[e:KNOWS]->(b) WHERE e.since > 2018 RETURN a.name, b.name")
              .to_a.map(&:sort)
    # 2018 edges (Alice→Carol, Dave→Eve) drop out; 2019, 2020 and 2021 stay.
    assert_equal [%w[Alice Bob], %w[Bob Dave], %w[Carol Dave]], rows
  end

  def test_a_type_alternation_is_refused_by_name
    e = assert_raises(Glyphes::UnsupportedError) do
      @db.query("MATCH (a)-[:KNOWS|WORKS_AT]->(b) RETURN b.name")
    end
    assert_includes e.message, "alternation"
  end

  # ---- ordering and paging -------------------------------------------

  def test_order_by_sorts_and_desc_reverses
    # Cypher's nulls rule (ops.nim cmpValues): null is larger than
    # everything, so it sorts last ascending and first descending.
    assert_equal [nil, 35, 30, 28, 25, 25],
                 col("MATCH (n:Person) RETURN n.age AS age ORDER BY age DESC")
    assert_equal [25, 25, 28, 30, 35, nil],
                 col("MATCH (n:Person) RETURN n.age AS age ORDER BY age")
  end

  def test_order_by_reads_the_alias_and_the_source_variable
    assert_equal %w[Alice Bob Carol Dave Eve Frank],
                 col("MATCH (n:Person) RETURN n.name AS name ORDER BY name")
    assert_equal %w[Alice Bob Carol Dave Eve Frank],
                 col("MATCH (n:Person) RETURN n.name AS name ORDER BY n.name")
    # A key over a variable the projection kept: n rides along behind the
    # projected columns (ops.nim okProject), so this is Cypher's rule and
    # not a lucky null that happens to compare equal. The youngest people
    # are Bob and Dave at 25; the tie is the scan's, not the sort's, so the
    # age is asserted and the name is not.
    assert_equal [25],
                 col("MATCH (n:Person) RETURN n.age AS age ORDER BY n.age LIMIT 1")
  end

  def test_skip_and_limit_page_the_sorted_stream
    ages = col("MATCH (n:Person) RETURN n.age AS age ORDER BY age")
    # The 25-25 tie is not pinned: which of Bob/Dave is first is the scan's
    # order, and a test that pinned it would assert an accident.
    assert_equal [25, 25, 28, 30, 35, nil], ages
    paged = col("MATCH (n:Person) RETURN n.age AS age ORDER BY age SKIP 2 LIMIT 2")
    assert_equal [28, 30], paged
  end

  def test_distinct_collapses_the_projection
    assert_equal ["Braga", "Faro", "Lisbon", "Porto", nil],
                 col("MATCH (n:Person) RETURN DISTINCT n.home AS h ORDER BY h")
  end

  # ---- unwind and with ------------------------------------------------

  def test_unwind_expands_a_list
    assert_equal [1, 2, 3], col("UNWIND [3, 1, 2] AS x RETURN x AS x ORDER BY x")
    assert_equal [1, 2, 3], col("UNWIND $list AS x RETURN x AS x", { "list" => [1, 2, 3] })
  end

  def test_with_projects_and_its_where_filters_the_new_scope
    assert_equal [28, 30, 35],
                 col("MATCH (n:Person) WITH n.age AS age WHERE age > 26 RETURN age ORDER BY age")
  end

  # ---- streaming ------------------------------------------------------

  def test_a_statement_streams_in_batches_and_closes
    st = @db.prepare("MATCH (n:Person) RETURN n.name AS name ORDER BY name")
    begin
      assert_equal ["name"], st.columns
      batches = []
      st.each_slice(4) { |b| batches << b }
      assert_equal [4, 2], batches.map(&:size)
      assert_equal %w[Alice Bob Carol Dave Eve Frank], batches.flatten
    ensure
      st.close
    end
    assert_predicate st, :closed?
    # R3 made `step` private; the post-close answer is still nil, reached
    # here through `send` because the assertion is about the engine
    # contract, not the visibility.
    assert_nil st.send(:step)
  end

  def test_close_is_idempotent
    st = @db.prepare("RETURN 1")
    st.close
    st.close
    assert_predicate st, :closed?
  end

  def test_query_materialises_the_same_rows_as_streaming
    streamed = []
    st = @db.prepare("MATCH (n:Person) WHERE n.home IS NOT NULL RETURN n.name AS name ORDER BY name")
    st.each_slice(1) { |b| streamed.concat(b.flatten) }
    st.close
    assert_equal %w[Alice Bob Carol Dave Frank], streamed
  end

  # ---- errors ---------------------------------------------------------

  def test_a_syntax_error_is_sql_with_position
    e = assert_raises(Glyphes::SqlError) { @db.query("SELEC 1") }
    assert_equal Glyphes::FFI::GLY_ERR_SQL, e.status
    assert_match(/1:1/, e.message)
  end

  def test_writes_are_refused_by_name_with_unsupported
    e = assert_raises(Glyphes::UnsupportedError) { @db.query("CREATE (n)") }
    assert_equal Glyphes::FFI::GLY_ERR_UNSUPPORTED, e.status
    assert_includes e.message, "CREATE"
  end

  def test_slice_refusals_name_the_construct
    {
      "MATCH (a) MATCH (b) RETURN 1" => "second MATCH",
      ## M5.5: OPTIONAL MATCH with nothing to its left is still refused, and
      ## the refusal says *why* — a left join needs a left side. The
      ## variable-length entry left this list when `*1..3` became legal; what
      ## is still refused in that corner is the path binding.
      "OPTIONAL MATCH (a) RETURN a" => "left",
      "MATCH p = (a)-[]->(b) RETURN p" => "path binding",
      ## M5.4 replaced this one: the aggregate is legal in a projection, so
      ## what stays refused is the aggregate in the *wrong place* — and the
      ## refusal still names the construct.
      "MATCH (a) WHERE count(*) > 1 RETURN a" => "aggregate",
      "MATCH (a) RETURN a UNION MATCH (b) RETURN b" => "UNION"
    }.each do |q, word|
      e = assert_raises(Glyphes::UnsupportedError) { @db.query(q) }
      assert_includes e.message, word, "refusal must name #{word}: #{e.message}"
    end
  end

  # ---- a writable open still reads -------------------------------------

  def test_a_writable_open_of_a_copy_reads_the_same_graph
    # The fixture has no snapshot: the generator committed once and closed,
    # and close does not checkpoint — so the whole graph lives in the log,
    # and a readonly open is a recovery. This copies the log alone and
    # proves the read path from a log-only database, writable or not.
    Dir.mktmpdir do |dir|
      path = File.join(dir, "copy.glyph")
      FileUtils.cp(FIXTURE + "-wal", path + "-wal")
      Glyphes::Database.open(path) do |wdb|
        names = wdb.query("MATCH (n:Person) RETURN n.name AS name ORDER BY name")
                    .to_a.map(&:first)
        assert_equal %w[Alice Bob Carol Dave Eve Frank], names
      end
    end
  end
end